export function invitationCategoryForActivity(activity?: string | null): InvitationCategory {
  const value = String(activity || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  return activityCategories.find(({ terms }) => terms.some((term) => value.includes(term)))?.category || "General";
}

function preferredDesignForActivity(activity?: string | null): InvitationDesignId | null {
  const value = String(activity || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  if (value.includes("movie")) return "outdoor-movie";
  if (value.includes("camp")) return "outdoor-campfire";
  if (value.includes("hike") || value.includes("hiking")) return "outdoor-mountain";
  if (value.includes("beach") || value.includes("pool")) return "outdoor-beach";
  if (value.includes("fish") || value.includes("lake")) return "outdoor-lakeside";
  if (value.includes("sport") || value.includes("game") || value.includes("field day")) return "outdoor-field-day";
  if (value.includes("tailgate")) return "cookout-tailgate";
  if (value.includes("picnic")) return "cookout-park-picnic";
  return null;
}

export function rankedInvitationDesigns(activity?: string | null) {
  const category = invitationCategoryForActivity(activity);
  const preferredId = preferredDesignForActivity(activity);
  return [...invitationDesigns].sort((left, right) => {
    const rank = (design: (typeof invitationDesigns)[number]) => design.id === preferredId ? 0 : design.category === category ? 1 : design.category === "General" ? 2 : 3;
    return rank(left) - rank(right);
  });
}

export function suggestedInvitationDesign(activity?: string | null): InvitationDesignId {
  const preferredId = preferredDesignForActivity(activity);
  if (preferredId) return preferredId;
  const category = invitationCategoryForActivity(activity);
  return invitationDesigns.find((design) => design.category === category)?.id || "general-sunlit";
}
