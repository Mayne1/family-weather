export function getInvitationDesign(value?: string | null) {
  return invitationDesigns.find((design) => design.id === value) || invitationDesigns.find((design) => design.id === "general-sunlit")!;
}

export type InvitationCategory = (typeof invitationDesigns)[number]["category"];

